"""
Export the trained GradientBoostingClassifier to a pure-data Python module
(api/model_data.py) so the serverless API needs neither pickle nor sklearn.

Run after training:  python training/export_model.py
"""
import json
import pickle
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
MODEL_DIR = ROOT / "api" / "model"
OUT = ROOT / "api" / "model_data.py"

with open(MODEL_DIR / "credit_model.pkl", "rb") as f:
    model = pickle.load(f)
scaler = json.load(open(MODEL_DIR / "scaler.json"))
features = json.load(open(MODEL_DIR / "features.json"))
metrics = json.load(open(MODEL_DIR / "metrics.json"))
metadata = json.load(open(MODEL_DIR / "metadata.json"))

# Raw init prediction (log-odds prior) taken from the fitted model itself
prior = float(model._raw_predict_init(np.zeros((1, model.n_features_in_)))[0][0])

trees = []
for est in model.estimators_[:, 0]:
    t = est.tree_
    trees.append({
        "f": t.feature.tolist(),  # -2 marks a leaf
        "t": [round(x, 10) for x in t.threshold.tolist()],
        "l": t.children_left.tolist(),
        "r": t.children_right.tolist(),
        "v": [round(float(v), 10) for v in t.value[:, 0, 0].tolist()],
    })

payload = {
    "prior": prior,
    "learning_rate": float(model.learning_rate),
    "trees": trees,
    "scaler_mean": scaler["mean"],
    "scaler_scale": scaler["scale"],
    "features": features,
    "feature_importances": {k: round(float(v), 6) for k, v in zip(features, model.feature_importances_)},
    "metrics": metrics,
    "metadata": metadata,
}

blob = json.dumps(payload, separators=(",", ":"))
module = (
    '"""Auto-generated by training/export_model.py — pure-data model payload.\n'
    'GradientBoostingClassifier trees flattened to arrays so inference needs only numpy.\n"""\n'
    "import json as _json\n\n"
    f"MODEL = _json.loads({blob!r})\n"
)
OUT.write_text(module)
print(f"wrote {OUT} ({len(module) / 1024:.0f} KB), {len(trees)} trees, prior={prior:.6f}")
